--- Check if a byte represents an instruction prefix (GC, Math, SIMD, Threads).
--- @param byte integer
--- @return boolean
function opcodes.is_prefix(byte)
	return byte == opcodes.PREFIX_GC
		or byte == opcodes.PREFIX_MATH
		or byte == opcodes.PREFIX_SIMD
		or byte == opcodes.PREFIX_THREADS
end

--- Convert a value type (integer or structured table) to its canonical WAT string representation.
--- @param valtype integer|table
--- @return string
function opcodes.valtype_to_string(valtype)
	if not valtype then
		return "unknown"
	end
	if type(valtype) == "table" then
		local ht = valtype.heap_type
		local ht_str = (type(ht) == "number" and opcodes.HEAP_TYPE_NAMES[ht]) or tostring(ht)
		if valtype.nullable then
			return string.format("(ref null %s)", ht_str)
		else
			return string.format("(ref %s)", ht_str)
		end
	end
	return opcodes.TYPE_NAMES[valtype]
		or (type(valtype) == "number" and string.format("unknown_type(0x%02X)", valtype) or tostring(valtype))
end

--- Get human-readable name for a section ID.
--- @param id integer
--- @return string
function opcodes.section_name(id)
	return opcodes.SECTION_NAMES[id] or "unknown"
end

--- Get human-readable name for an import/export descriptor type.
--- @param desc integer
--- @return string
function opcodes.desc_name(desc)
	return opcodes.DESC_NAMES[desc] or string.format("desc_%d", desc)
end

--- Get human-readable name for a heap type.
--- @param ht integer|string
--- @return string
function opcodes.heap_type_name(ht)
	return (type(ht) == "number" and opcodes.HEAP_TYPE_NAMES[ht]) or tostring(ht)
end

